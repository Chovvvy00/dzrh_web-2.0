export type SearchArticle = {
	id: string;
	title: string;
	category: string;
	image?: string;
	excerpt?: string;
};

const groups = [
	{ category: 'Breaking News', articles: [breakingNews] },
	{ category: 'Headlines', articles: headlines },
	{ category: 'Nation', articles: nationArticles },
	{ category: 'Entertainment', articles: entertainmentArticles },
	{ category: 'World', articles: worldArticles },
	{ category: 'Metro Manila', articles: metroManilaArticles },
	{ category: 'Province', articles: provinceArticles },
	{ category: 'Asia', articles: asiaArticles },
	{ category: 'Business', articles: businessArticles },
	{ category: 'Lifestyle', articles: lifestyleArticles },
	{ category: 'Featured', articles: [featuredArticle] },
	{ category: 'Trending', articles: trendingArticles },
	{ category: 'Most Read', articles: mostReadArticles }
];

export const searchableArticles: SearchArticle[] = groups.flatMap(({ category, articles }) =>
	articles.map((article, index) => ({ ...article, id: `${category}-${index}`, category }))
);

export function searchArticles(query: string): SearchArticle[] {
	const terms = query.trim().toLowerCase().split(/\s+/).filter(Boolean);
	if (!terms.length) return [];
	return searchableArticles.filter((article) => {
		const text = `${article.title} ${article.excerpt ?? ''} ${article.category}`.toLowerCase();
		return terms.every((term) => text.includes(term));
	});
}
